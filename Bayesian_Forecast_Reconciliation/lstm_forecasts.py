import torch
import torch.nn as nn
import numpy as np
import pandas as pd
import yfinance as yf

# 1. Data Setup (Identical to your Darts logic)
spy = yf.download('SPY', start='2023-12-01', end='2025-12-31', progress=False, auto_adjust=True)
spy['returns'] = spy['Close'].pct_change()
spy['volatility'] = spy['returns'].rolling(window=5).std() * np.sqrt(252)
spy = spy.dropna()
y_all = spy['volatility'].values

T = len(y_all)
H = 5
lookback = 20
window_size = 100
T_test = 100

# 2. Define a Simple Direct Multi-Step LSTM
class DirectLSTM(nn.Module):
    def __init__(self, input_size=1, hidden_size=32, output_size=H):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, batch_first=True)
        self.linear = nn.Linear(hidden_size, output_size)

    def forward(self, x):
        # x shape: (batch, lookback, 1)
        lstm_out, _ = self.lstm(x)
        # Take the last hidden state to predict all H steps directly
        last_hidden = lstm_out[:, -1, :]
        return self.linear(last_hidden)

# 3. Rolling Forecast Loop
forecast_matrix = np.full((T_test, H), np.nan)
device = torch.device("cpu")
print("Training rolling PyTorch LSTM models...")

for i in range(T_test):
    # Define training window
    train_end = T - T_test + i
    train_start = train_end - window_size
    train_data = y_all[train_start:train_end]

    # Prepare sequences for LSTM
    X, Y = [], []
    for j in range(len(train_data) - lookback - H + 1):
        X.append(train_data[j : j + lookback])
        Y.append(train_data[j + lookback : j + lookback + H])

    X_tensor = torch.tensor(np.array(X), dtype=torch.float32).unsqueeze(-1).to(device)
    Y_tensor = torch.tensor(np.array(Y), dtype=torch.float32).to(device)

    # Initialize model, loss, optimizer
    model = DirectLSTM().to(device)
    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=0.01)

    # Train for a few epochs (minimal for speed)
    model.train()
    for epoch in range(15):
        optimizer.zero_grad()
        output = model(X_tensor)
        loss = criterion(output, Y_tensor)
        loss.backward()
        optimizer.step()

    # Predict
    model.eval()
    with torch.no_grad():
        last_seq = train_data[-lookback:]
        last_tensor = torch.tensor(last_seq, dtype=torch.float32).unsqueeze(0).unsqueeze(-1).to(device)
        pred = model(last_tensor).cpu().numpy().flatten()
        forecast_matrix[i, :] = pred

    if i % 20 == 0:
        print(f"  Progress: {i}/{T_test}")

# 4. Save for R
lstm_df = pd.DataFrame(forecast_matrix, columns=[f"h{h+1}" for h in range(H)])
lstm_df.to_csv("lstm_forecasts.csv", index=False)
print("Saved lstm_forecasts.csv")